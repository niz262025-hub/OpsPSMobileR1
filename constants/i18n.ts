export function normalizeLanguagePreference(
  value: string | null | undefined,
): Language {
  if (!value) return FALLBACK_LANGUAGE;

  return (
    LANGUAGE_ALIASES[value]
    ?? LANGUAGE_ALIASES[value.toLowerCase()]
    ?? LANGUAGE_ALIASES[value.toUpperCase()]
    ?? FALLBACK_LANGUAGE
  );
}

